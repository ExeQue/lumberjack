import type { ReactNode } from 'react';
import { cn } from '@/lib/utils';

/**
 * A QR code rendered on the server as SVG (amber on the dark panel, with the mark),
 * with a text label for screen readers.
 */
export function QrCode({
    svg,
    label,
    className,
}: {
    svg: string;
    label: string;
    className?: string;
}) {
    return (
        <div
            role="img"
            aria-label={label}
            className={cn(
                'overflow-hidden rounded-2xl border-2 border-[#333a41] bg-[#161a1e] [&>svg]:block [&>svg]:size-full',
                className,
            )}
            // Generated by exeque/laravel-qr from our own URL; its logo is sanitized.
            dangerouslySetInnerHTML={{ __html: svg }}
        />
    );
}

/** An address as people type it: without https:// and a trailing slash. */
export function bareUrl(url: string): string {
    return url.replace(/^https?:\/\//, '').replace(/\/$/, '');
}

const SLOT = '\u0000';

/**
 * A translated line with an element (an address in mono, say) where its placeholder
 * was: t(key, { url: SLOT }) split around the slot.
 */
export function withSlot(
    translate: (replace: Record<string, string>) => string,
    name: string,
    node: ReactNode,
): ReactNode {
    const [before, ...after] = translate({ [name]: SLOT }).split(SLOT);

    return (
        <>
            {before}
            {node}
            {after.join('')}
        </>
    );
}
